// 계산 유틸
// ───────────────────────────────────────────────

export function calcGrowthRate(current: number, base: number): number {
  if (!base) return 0;
  return ((current - base) / base) * 100;
}

export function calcRegisteredFromRate(base: number, growthRate: number): number {
  return Math.round(base * (1 + growthRate / 100));
}

export function calcAvgRate(values: number[], bases: number[]): number {
  if (!values.length) return 0;
  const rates = values.map((v, i) => bases[i] ? (v / bases[i]) * 100 : 0);
  return rates.reduce((a, b) => a + b, 0) / rates.length;
}
